### **3.1 登顶世界第一 (2018)**

2018年是属于樊振东的一年。凭借在3月卡塔尔公开赛上包揽男单、男双两项冠军的出色表现，他在4月的国际乒联世界排名中，正式超越德国名将蒂莫·波尔，职业生涯首次登顶世界第一。

成为世界第一后，樊振东用一系列冠军证明了自己的实力。在瑞典哈尔姆斯塔德举行的世界乒乓球团体锦标赛上，他作为绝对主力，帮助中国队实现九连冠。8月的雅加达亚运会，他更是一人独得男子团体与男子单打两枚金牌，彻底确立了自己在亚洲的霸主地位。10月，在巴黎举行的男子世界杯上，他在决赛中击败波尔，成功卫冕，第二次捧起世界杯冠军奖杯。此外，他还赢得了当年的亚洲杯男单冠军。

